// 字典内容是静态的，只合并一次，避免渲染每张卡片时反复复制整份语言包。
const appLanguageDictionaries = new Map();

export function translateAppText(language, key, vars = null) {
  const lang = Object.hasOwn(I18N, language) ? language : "en";
  let dict = appLanguageDictionaries.get(lang);
  if (!dict) {
    const base = lang === "zh-TW" ? I18N["zh-CN"] : I18N.en;
    dict = Object.freeze({ ...base, ...I18N[lang] });
    appLanguageDictionaries.set(lang, dict);
  }
  const text = dict[key] || I18N.en?.[key] || I18N["zh-CN"]?.[key] || key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? "");
}
