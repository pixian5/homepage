const popupLanguageDictionaries = new Map();

export function translatePopupText(language, key, vars = null) {
  const normalized = normalizeLanguage(language) || "zh-CN";
  const lang = Object.hasOwn(POPUP_I18N, normalized) ? normalized : "en";
  let dict = popupLanguageDictionaries.get(lang);
  if (!dict) {
    const base = lang === "zh-TW" ? POPUP_I18N["zh-CN"] : POPUP_I18N.en;
    dict = Object.freeze({ ...base, ...POPUP_I18N[lang] });
    popupLanguageDictionaries.set(lang, dict);
  }
  const text = dict[key] || POPUP_I18N.en?.[key] || POPUP_I18N["zh-CN"]?.[key] || key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? "");
}
